package xpath

import "fmt"

// isNumericType is warn_is_numeric_type: an integer or decimal64 type, a union with such a member
// or a leafref to one.
func isNumericType(t SchemaType) bool {
	switch t.Base() {
	case TypeDec64, TypeInt8, TypeUint8, TypeInt16, TypeUint16, TypeInt32, TypeUint32, TypeInt64, TypeUint64:
		return true
	case TypeUnion:
		for _, m := range t.Union() {
			if isNumericType(m) {
				return true
			}
		}
	case TypeLeafref:
		return isNumericType(t.Realtype())
	}
	return false
}

// isStringType is warn_is_string_type: bits, enumeration, identityref, instance-identifier or
// string, also as a union member or behind a leafref.
func isStringType(t SchemaType) bool {
	switch t.Base() {
	case TypeBits, TypeEnum, TypeIdent, TypeInst, TypeString:
		return true
	case TypeUnion:
		for _, m := range t.Union() {
			if isStringType(m) {
				return true
			}
		}
	case TypeLeafref:
		return isStringType(t.Realtype())
	}
	return false
}

// isSpecificType is warn_is_specific_type: t, a union member or a leafref target has base type b.
func isSpecificType(t SchemaType, b BaseType) bool {
	switch t.Base() {
	case b:
		return true
	case TypeUnion:
		for _, m := range t.Union() {
			if isSpecificType(m, b) {
				return true
			}
		}
	case TypeLeafref:
		return isSpecificType(t.Realtype(), b)
	}
	return false
}

// flatMembers appends the members warn_is_equal_type_next_type yields for t, in order: a leafref is
// followed to its realtype, a union recursed, anything else is a member.
func flatMembers(t SchemaType, out []SchemaType) []SchemaType {
	if t.Base() == TypeLeafref {
		t = t.Realtype()
	}
	if t.Base() != TypeUnion {
		return append(out, t)
	}
	for _, m := range t.Union() {
		out = flatMembers(m, out)
	}
	return out
}

// equalType is warn_is_equal_type: some member of t1 has the base type of some member of t2.
// libyang resumes its walk after the previous member found by pointer identity
// (warn_is_equal_type_next_type), so a union that repeats one type object makes it cycle forever
// whenever no base matches (D-0015). This walks the flattened members by index instead: the same
// answer whenever libyang terminates, and it terminates.
func equalType(t1, t2 SchemaType) bool {
	m2 := flatMembers(t2, nil)
	for _, x := range flatMembers(t1, nil) {
		for _, y := range m2 {
			if x.Base() == y.Base() {
				return true
			}
		}
	}
	return false
}

// kindStr is lys_nodetype2str: input and output are "unknown" there.
func kindStr(k Kind) string {
	switch k {
	case KindContainer:
		return "container"
	case KindChoice:
		return "choice"
	case KindLeaf:
		return "leaf"
	case KindLeafList:
		return "leaf-list"
	case KindList:
		return "list"
	case KindAnyxml:
		return "anyxml"
	case KindAnydata:
		return "anydata"
	case KindCase:
		return "case"
	case KindRPC:
		return "RPC"
	case KindAction:
		return "action"
	case KindNotif:
		return "notification"
	}
	return "unknown"
}

// warnSubexpr is warn_subexpr_log: 20 bytes of the expression from tokPos (C "%.*s" stops at the
// end of the string), with the path of the expression's context node ("/" when it is the root).
func (a *atomizer) warnSubexpr(tokPos int) {
	cur := "/"
	if a.cur != nil {
		cur = a.cur.Path()
	}
	sub := a.src[min(tokPos, len(a.src)):]
	if len(sub) > 20 {
		sub = sub[:20]
	}
	a.warn(fmt.Sprintf("Previous warning generated by XPath subexpression[%d] \"%s\" with context node \"%s\".", tokPos, sub, cur))
}

// warnOperands is warn_operands: the operands of an operator, as the last node in context of each
// set (s2 nil for the unary minus), checked for node type and, with numbersOnly, for a numeric
// type; without it two leaves must have compatible types. tokPos is the offset libyang names the
// subexpression by.
func (a *atomizer) warnOperands(s1, s2 *scset, numbersOnly bool, tokPos int) {
	if a.warn == nil {
		return
	}
	n1 := lastCtx(s1)
	var n2 SchemaNode
	if s2 != nil {
		n2 = lastCtx(s2)
	}
	if n1 == nil && n2 == nil {
		return
	}
	leaves, warning := true, false
	check := func(n SchemaNode) {
		if n == nil {
			return
		}
		switch k := n.Kind(); {
		case k != KindLeaf && k != KindLeafList:
			a.warn(fmt.Sprintf("Node type %s \"%s\" used as operand.", kindStr(k), n.Name()))
			warning, leaves = true, false
		case numbersOnly && !isNumericType(n.Type()):
			a.warn(fmt.Sprintf("Node \"%s\" is not of a numeric type, but used where it was expected.", n.Name()))
			warning = true
		}
	}
	check(n1)
	check(n2)
	if n1 != nil && n2 != nil && leaves && !numbersOnly {
		num1, num2 := isNumericType(n1.Type()), isNumericType(n2.Type())
		if num1 != num2 || (!num1 && !equalType(n1.Type(), n2.Type())) {
			a.warn(fmt.Sprintf("Incompatible types of operands \"%s\" and \"%s\" for comparison.", n1.Name(), n2.Name()))
			warning = true
		}
	}
	if warning {
		a.warnSubexpr(tokPos)
	}
}
